package main

import (
	"bufio"
	"fmt"
	"os"
)

/*
题目描述：

拼多多正在举行“百亿补贴·神秘三件套”大促活动。

参加活动的用户必须从拼多多商城中价格为 1 到 n 元的商品中，
恰好挑选三件商品。设三件商品的单价分别为 a、b、c，
并用它们组成一个盲盒套餐。

为了防止恶意薅羊毛，多多安全系统为盲盒套餐设置了严格的
风控规则。只有同时满足以下所有条件的三件商品，才能下单：

1. 价格非减规则
   三件商品的价格必须满足：
   1 <= a < b < c <= n

2. 异或为 0
   为了增加趣味性，三件商品价格的二进制异或和必须为 0：
   a XOR b XOR c = 0

3. 三角形原则
   任意两件商品的价格之和，都必须严格大于第三件商品的价格。
   由于已经满足 a < b < c，因此只需要保证：
   a + b > c

请计算一共有多少种满足条件的盲盒套餐。


输入描述：

第一行输入一个整数 n，表示商品价格范围为 1 到 n 元。
1 <= n <= 2500


输出描述：

输出一个整数，表示满足所有条件的盲盒套餐数量。


样例 1：

输入：
6

输出：
1

样例解释：
满足条件的商品价格组合为：
(3, 5, 6)


样例 2：

输入：
10

输出：
2
*/

func solution(n int) int {
	if n <= 3 {
		return 0
	}
	var result int
	for a := 1; a <= n-2; a++ {
		for b := a + 1; b <= n-1; b++ {
			c := a ^ b
			if a+b > c && c > b && c <= n {
				result++
			}
		}
	}
	return result
}

func main() {
	in := bufio.NewReader(os.Stdin)
	var n int
	fmt.Fscan(in, &n)
	fmt.Println(solution(n))
}
